import {schemaScalarClassifications} from "./schema_contract.mjs";
import {checkFreshness} from "./generate_cose_contract.mjs";
import {maskRustNonCode} from "./release-readiness/operation-contract-routing.mjs";

// The pinned shared runner retains its supply-chain and general repository
// checks. Its legacy protobuf helper requires source patches; enforce the
// native generator contract here without modifying that immutable dependency.
export function assertGuardedBuffaContract({root,readText,fail,assertWorkflowRunStep,installBufRun},freshness) {
  const config=readText("buf.gen.yaml");
  const required=[
    "views=true","json=true","deny_unknown_json_fields=true","unknown_fields=false",
    "zeroize_in=.reallyme.cose.v1",
    "bytes_type_custom_in=.reallyme.cose.v1=crate::SecretBytes",
    "string_type_custom_in=.reallyme.cose.v1=crate::SecretString",
    "json_policy_type=crate::SecretBytes","json_policy_type=crate::SecretString",
    "deny_view_json=.reallyme.cose.v1",
  ];
  const options=[...config.matchAll(/^\s+- ([a-z_]+=\S+)\s*$/gmu)].map(([,value])=>value);
  if(options.length!==required.length || required.some(value=>!options.includes(value))) fail("native Buffa cleanup configuration differs from its audited contract");
  for(const name of ["protoc-gen-reallyme-buffa","protoc-gen-reallyme-buffa-packaging"]) {
    if(!config.includes(`local: ${name}\n`)) fail("ReallyMe local generator executable required");
  }
  if((config.match(/strategy: all/gu)??[]).length!==2) fail("whole-project generator selector validation required");
  for(const path of ["Cargo.toml","fuzz/Cargo.toml"]) {
    if(!readText(path).includes('buffa = { package = "reallyme-buffa", version = "=0.1.2", features = ["json", "zeroize"] }')) fail("exact ReallyMe Buffa dependency family required");
  }
  const schema=readText("crates/proto/proto/reallyme/cose/v1/cose.proto");
  const generated=readText("crates/proto/src/generated/buffa/reallyme.cose.v1.cose.rs");
  if(!generated.startsWith("// @generated by reallyme-buffa-codegen 0.1.2.")) fail("matching native generator output required");
  const executable=maskRustNonCode(generated);
  const oneofs=maskRustNonCode(readText("crates/proto/src/generated/buffa/reallyme.cose.v1.cose.__oneof.rs"));
  if(/__buffa_unknown_fields|__reallyme_zeroize|crate::merge_sensitive/u.test(executable)) fail("obsolete generated-source cleanup detected");
  for(const [,name] of schema.matchAll(/^enum (\w+) \{/gmu)) {
    const deserializer=new RegExp(`impl<'de> ::serde::Deserialize<'de> for ${name} \\{([\\s\\S]*?)\\n\\}`,"u").exec(executable)?.[1];
    if(!deserializer?.includes("::buffa::json_helpers::closed_enum::deserialize_strict(d)")) fail("standalone enums must use native fixed JSON diagnostics");
  }
  for(const [,name] of schema.matchAll(/^message (\w+) \{/gmu)) {
    for(const trait of ["Zeroize","ZeroizeOnDrop"]) {
      if(!executable.includes(`impl ::buffa::sensitive::${trait} for ${name}`)) fail("every message must join the native cleanup family");
    }
    if(!executable.includes(`impl ::core::ops::Drop for ${name}`)) fail("every message needs native Drop");
  }
  // Classifications remain at the schema field. Both public metadata and
  // sensitive scalars use guarded storage under this complete cleanup profile.
  for(const {message,field,kind} of schemaScalarClassifications(schema)) {
    const start=executable.indexOf(`pub struct ${message} {`);
    const end=executable.indexOf("\n}",start);
    const body=executable.slice(start,end);
    const expected=kind==="bytes"?"SecretBytes":"SecretString";
    const fieldType=`(?:(?:::core::option::Option|::buffa::sensitive::List)<)?crate::${expected}>?`;
    if(!new RegExp(`pub ${field}:\\s*${fieldType}\\s*,`,"u").test(body)) {
      const schemaBody=new RegExp(`message ${message} \\{([\\s\\S]*?)\\n\\}`,"u").exec(schema)?.[1]??"";
      const oneof=/oneof (\w+) \{([\s\S]*?)\n\s*\}/u.exec(schemaBody);
      const variant=field.split("_").map(part=>part[0].toUpperCase()+part.slice(1)).join("");
      const module=message.replace(/([a-z0-9])([A-Z])/gu,"$1_$2").toLowerCase();
      const scope=new RegExp(`pub mod ${module} \\{([\\s\\S]*?)(?=\\npub mod |$)`,"u").exec(oneofs)?.[1]??"";
      if(oneof===null || !new RegExp(`\\b${field} = \\d+;`,"u").test(oneof[2])
        || !new RegExp(`${variant}\\(crate::${expected}\\)`,"u").test(scope)) fail("protobuf scalar lacks its native wipe owner");
    }
  }
  const workflow=".github/workflows/protobuf-ci.yml";
  if(!/^\s*BUFFA_VERSION: 0\.1\.2$/mu.test(readText(workflow))) fail("generator CI version differs");
  if(!/^\s*BUF_VERSION: 1\.73\.0$/mu.test(readText(workflow))) fail("Buf CI version differs");
  assertWorkflowRunStep(workflow,"Install pinned Buffa generators",`cargo install reallyme-protoc-gen-buffa --version "=$BUFFA_VERSION" --locked
cargo install reallyme-protoc-gen-buffa-packaging --version "=$BUFFA_VERSION" --locked
test "$(protoc-gen-reallyme-buffa --version)" = "protoc-gen-reallyme-buffa $BUFFA_VERSION"
test "$(protoc-gen-reallyme-buffa-packaging --version)" = "protoc-gen-reallyme-buffa-packaging $BUFFA_VERSION"`);
  if(installBufRun!==undefined) assertWorkflowRunStep(workflow,"Install buf",installBufRun);
  assertWorkflowRunStep(workflow,"Check release readiness generated freshness",
    "node .release-readiness/scripts/run-consumer-check.mjs --generated-freshness");
  if(freshness) checkFreshness(root);
}
