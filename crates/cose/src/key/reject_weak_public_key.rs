pub(super) fn reject_weak_public_key(
    algorithm: Algorithm,
    public_key: &[u8],
) -> Result<(), CoseError> {
    if algorithm != Algorithm::Ed25519 {
        return Ok(());
    }

    let public_key = <&[u8; ED25519_PUBLIC_KEY_BYTES]>::try_from(public_key)
        .map_err(|_| CoseError::InvalidKeyMaterial)?;
    if ED25519_LOW_ORDER_ENCODINGS.contains(public_key) {
        return Err(CoseError::InvalidKeyMaterial);
    }

    Ok(())
}
